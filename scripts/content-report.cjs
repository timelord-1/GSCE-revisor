const fs = require('fs');
const path = require('path');
const deck = require('../src/deck.js');
const source = deck.specification;
const escape = value => String(value).replace(/\|/g, '\\|');
const lines = [
 '# Specification-to-card map', '',
 `Qualification: ${source.qualification}. Audited on ${source.auditedOn} against the user-provided saved AQA webpage and its embedded specification data.`, '',
 `Source: [AQA specification](${source.sourceUrl}). Uploaded file: \`${source.sourceFile}\`.`, '',
 `Source file SHA-256: \`${source.sourceSha256}\`.`, '',
 `${deck.cards.length} cards (${deck.cards.filter(c => c.tier === 'higher').length} Higher-only), ${deck.topics.length} topics, ${source.sections.length} subject-content sections and ${source.practicalCount} required practical activities.`, '',
 'Each listed subject-content section has at least one referenced revision card. This establishes section coverage, not exhaustive coverage of every possible exam question or mastery of drawing and practical work. “Mixed” means the section contains both Foundation content and Higher-only clauses; each card has its own tier label.', '',
 '| Section | AQA title | Section tier scope | Referenced card IDs |',
 '|---|---|---|---|'
];
for (const section of source.sections) {
 const cards = deck.cards.filter(c => c.specRefs.includes(section.ref));
 if (!cards.length) throw new Error('Uncovered specification section: ' + section.ref);
 lines.push(`| ${section.ref} | ${escape(section.title)} | ${section.tierScope} | ${cards.map(c => c.id).join(', ')} |`);
}
lines.push('', '## Required practical activities', '', '| Activity | Referenced practical cards |', '|---|---|');
for (let number = 1; number <= source.practicalCount; number++) {
 const cards = deck.cards.filter(c => c.practical === number);
 if (!cards.length) throw new Error('Uncovered practical: ' + number);
 lines.push(`| ${number} | ${cards.map(c => c.id).join(', ')} |`);
}
lines.push('', 'Generated by `npm run content:report` from `src/deck.js`. The full copyrighted AQA specification is not redistributed here.', '');
fs.writeFileSync(path.join(__dirname, '../docs/SPECIFICATION-MAP.md'), lines.join('\n'));
console.log(`Wrote specification map for ${source.sections.length} sections and ${source.practicalCount} practicals.`);
